const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { ResearchStore, fields } = require('./electron/research/store');

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'neochat-research-test-'));
try {
  const store = new ResearchStore(directory);
  assert.deepEqual(store.list(), []);
  const draft = Object.fromEntries(fields.map(field => [field, '']));
  assert.throws(() => store.save(draft), /título/);
  const first = store.save({ ...draft, title: ' Minha revisão ', questions: 'Como apoiar a aprendizagem?\nQuais métodos?', population: 'Estudantes' });
  assert.equal(first.title, 'Minha revisão');
  assert.equal(first.revision, 1);
  const reopened = new ResearchStore(directory).get(first.id);
  assert.deepEqual(reopened, first);
  const updated = store.save({ ...reopened, inclusion: 'Estudos empíricos' });
  assert.equal(updated.revision, 2);
  assert.equal(updated.createdAt, first.createdAt);
  assert.equal(store.list().length, 1);
  assert.throws(() => store.save(first), /mudou/);
  assert.throws(() => store.get('../../settings'), /inválido/);
  assert.throws(() => store.save({ ...updated, questions: {} }), /Campo inválido/);
  assert.deepEqual(store.get(updated.id), updated);
  const ris = 'TY  - JOUR\nTI  - Learning with AI\nAU  - Silva, Ana\nPY  - 2025\nDO  - 10.123/test\nAB  - Evidence\n  continued\nER  - \n';
  const imported = store.importRis({ id: updated.id, revision: updated.revision, text: ris + ris });
  assert.equal(imported.duplicates, 1);
  assert.equal(imported.project.references.length, 2);
  assert.equal(imported.project.references[0].abstract, 'Evidence continued');
  assert.equal(imported.project.references[1].duplicateOf, imported.project.references[0].id);
  assert.throws(() => store.importRis({ id: updated.id, revision: imported.project.revision, text: 'TY  - JOUR\nTI  - Broken' }), /incompleto/);
  assert.equal(store.get(updated.id).revision, imported.project.revision);
  assert.throws(() => store.save({ ...imported.project, references: imported.project.references.map(item => ({ ...item, screening: 'exclude' })) }), /motivo/);
  assert.throws(() => store.save({ ...imported.project, references: imported.project.references.map(item => ({ ...item, fullText: 'include' })) }), /triagem/);
  const screened = store.save({ ...imported.project, references: imported.project.references.map(item => ({ ...item, screening: 'exclude', screeningReason: 'Fora do período' })) });
  assert.equal(screened.history.length, 2);
  assert.equal(screened.history[0].actor, 'researcher');
  const fieldId = require('crypto').randomUUID();
  const assessment = { ...screened.assessment, extractionFields: [{ id: fieldId, label: 'Método' }], answers: [{ referenceId: screened.references[0].id, fieldId, value: 'Experimento', evidence: 'We conducted an experiment', page: '4' }] };
  const extracted = store.save({ ...screened, assessment });
  assert.equal(store.get(extracted.id).assessment.answers[0].page, '4');
  assert.throws(() => store.save({ ...extracted, assessment: { ...assessment, extractionFields: [] } }), /Resposta inválida/);
  assert.throws(() => store.save({ ...extracted, assessment: { ...assessment, answers: [...assessment.answers, ...assessment.answers] } }), /Resposta inválida/);
  assert.throws(() => store.attachPdf(extracted.id, extracted.references[0].id, Buffer.from('not a PDF')), /PDF válido/);
  store.attachPdf(extracted.id, extracted.references[0].id, Buffer.from('%PDF-1.4\n%%EOF'));
  const restored = store.restore(store.backup(extracted.id));
  assert.notEqual(restored.id, extracted.id);
  assert.equal(restored.references[0].hasPdf, true);
  assert.deepEqual(restored.history, extracted.history);
  assert.deepEqual(restored.assessment, extracted.assessment);
  const { exportCsv } = require('./electron/research/export');
  const csv = exportCsv({ ...restored, references: restored.references.map(item => ({ ...item, title: '=danger,"quoted"' })) });
  assert.ok(csv.includes("'=danger,"));
  assert.ok(csv.includes('""quoted""'));
  const { parseBibtex } = require('./electron/research/bibtex');
  const bib = '@string{venue = "Science"}\n@comment{Ignore {nested} content}\n@article{key, title={A {nested} title}, author="Silva and Souza", journal=venue # " Journal", year=2025, doi={10.1/example}, abstract={Evidence}}';
  const parsed = parseBibtex(bib);
  assert.equal(parsed[0].source, 'Science Journal');
  assert.equal(parsed[0].title, 'A {nested} title');
  assert.equal(parsed[0].year, '2025');
  assert.throws(() => parseBibtex('@article{key, title={Unclosed}'), /fechamento/);
  assert.throws(() => parseBibtex('@article{key, title=unknown}'), /macro não definida/);
  const bibProject = store.importReferences({ id: restored.id, revision: restored.revision, text: bib, format: 'bib' }).project;
  assert.equal(bibProject.references.length, 3);
  const { exportMarkdown } = require('./electron/research/export');
  assert.ok(exportMarkdown(bibProject).includes('Experimento'));
  assert.ok(exportMarkdown(bibProject).includes('## Perguntas'));
  console.log('Research: persistence, validation, traversal and revision conflict checks passed.');
} finally {
  fs.rmSync(directory, { recursive: true, force: true });
}
